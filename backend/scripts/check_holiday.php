<?php
/**
 * 祝日計算の自己チェック。内閣府が公示した 2026年・2027年の祝日と突き合わせる。
 * 実行: docker compose exec backend php scripts/check_holiday.php
 *
 * フロント側と同じ期待値を使っている。片方だけ直すとここで落ちる。
 */
require_once __DIR__ . '/../src/Utility/JapaneseHoliday.php';

use App\Utility\JapaneseHoliday;

// 内閣府「国民の祝日について」より
$expected = [
    2026 => [
        '2026-01-01' => '元日', '2026-01-12' => '成人の日', '2026-02-11' => '建国記念の日',
        '2026-02-23' => '天皇誕生日', '2026-03-20' => '春分の日', '2026-04-29' => '昭和の日',
        '2026-05-03' => '憲法記念日', '2026-05-04' => 'みどりの日', '2026-05-05' => 'こどもの日',
        '2026-05-06' => '振替休日', '2026-07-20' => '海の日', '2026-08-11' => '山の日',
        '2026-09-21' => '敬老の日', '2026-09-22' => '国民の休日', '2026-09-23' => '秋分の日',
        '2026-10-12' => 'スポーツの日', '2026-11-03' => '文化の日', '2026-11-23' => '勤労感謝の日',
    ],
    2027 => [
        '2027-01-01' => '元日', '2027-01-11' => '成人の日', '2027-02-11' => '建国記念の日',
        '2027-02-23' => '天皇誕生日', '2027-03-21' => '春分の日', '2027-03-22' => '振替休日',
        '2027-04-29' => '昭和の日', '2027-05-03' => '憲法記念日', '2027-05-04' => 'みどりの日',
        '2027-05-05' => 'こどもの日', '2027-07-19' => '海の日', '2027-08-11' => '山の日',
        '2027-09-20' => '敬老の日', '2027-09-23' => '秋分の日', '2027-10-11' => 'スポーツの日',
        '2027-11-03' => '文化の日', '2027-11-23' => '勤労感謝の日',
    ],
];

$failed = false;

foreach ($expected as $year => $want) {
    // その年の全日をなめて、祝日の集合が一致することを確かめる
    $got = [];
    $d   = new DateTime("$year-01-01");
    while ((int)$d->format('Y') === $year) {
        $name = JapaneseHoliday::name($d);
        if ($name !== null) {
            $got[$d->format('Y-m-d')] = $name;
        }
        $d->modify('+1 day');
    }
    if ($got !== $want) {
        $failed = true;
        fwrite(STDERR, "{$year}年の祝日が公示と一致しない\n");
        foreach (array_diff_assoc($got, $want) as $k => $v) {
            fwrite(STDERR, "  余分/相違: $k = $v\n");
        }
        foreach (array_diff_assoc($want, $got) as $k => $v) {
            fwrite(STDERR, "  不足: $k = $v\n");
        }
    }
}

// 平日・土日の判定
$cases = [
    ['2026-09-24', false], // 木曜
    ['2026-09-26', true],  // 土曜
    ['2026-09-27', true],  // 日曜
    ['2026-09-22', true],  // 国民の休日
];
foreach ($cases as [$date, $want]) {
    if (JapaneseHoliday::isClosed(new DateTime($date)) !== $want) {
        $failed = true;
        fwrite(STDERR, "isClosed($date) が期待と違う\n");
    }
}

if ($failed) {
    exit(1);
}
echo "祝日チェック OK（2026年・2027年）\n";
